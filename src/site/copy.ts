export function money(amountFcfa: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "fr" ? "fr-FR" : "en-GB")
    .format(amountFcfa)
    .replaceAll("\u202f", "\u00a0");
}

export function otherLocale(locale: Locale): Locale {
  return locale === "fr" ? "en" : "fr";
}
